import { request } from '../utils/request.js'

export const api = {
  home: () => request('/front/books/home'),
  categories: () => request('/front/categories'),
  books: (params) => request('/front/books', { params }),
  rank: (type) => request(`/front/ranks/${type}`),
  book: (id) => request(`/front/books/${id}`),
  chapters: (id, params) => request(`/front/books/${id}/chapters`, { params }),
  chapter: (id) => request(`/front/chapters/${id}`),
  visit: (id) => request(`/front/books/${id}/visit`, { method: 'POST' }),
  comments: (id, params) => request(`/front/books/${id}/comments`, { params }),
  replies: (id, commentId, params) => request(`/front/books/${id}/comments/${commentId}/replies`, { params }),
  comment: (id, data) => request(`/front/me/books/${id}/comments`, { method: 'POST', data, auth: true }),
  captcha: () => request('/front/auth/captcha'),
  login: (data) => request('/front/auth/login', { method: 'POST', data }),
  register: (data) => request('/front/auth/register', { method: 'POST', data }),
  me: () => request('/front/me/me', { auth: true }),
  updateMe: (data) => request('/front/me/me', { method: 'PUT', data, auth: true }),
  bookshelf: () => request('/front/me/bookshelf', { auth: true }),
  addShelf: (id) => request(`/front/me/bookshelf/${id}`, { method: 'PUT', auth: true }),
  removeShelf: (id) => request(`/front/me/bookshelf/${id}`, { method: 'DELETE', auth: true }),
  history: (params) => request('/front/me/history', { params, auth: true }),
  progress: (data) => request('/front/me/progress', { method: 'PUT', data, auth: true }),
  following: () => request('/front/me/following', { auth: true }),
  follow: (id) => request(`/front/me/following/${id}`, { method: 'PUT', auth: true }),
  unfollow: (id) => request(`/front/me/following/${id}`, { method: 'DELETE', auth: true }),
  markRead: (id) => request(`/front/me/following/${id}/read`, { method: 'PUT', auth: true }),
  imports: (params) => request('/front/me/imports', { params, auth: true }),
  import: (id) => request(`/front/me/imports/${id}`, { auth: true }),
  importChapters: (id, params) => request(`/front/me/imports/${id}/chapters`, { params, auth: true }),
  importChapter: (id, chapterId) => request(`/front/me/imports/${id}/chapters/${chapterId}`, { auth: true }),
  importProgress: (id, chapterId) => request(`/front/me/imports/${id}/progress`, { method: 'PUT', data: { chapterId }, auth: true }),
  deleteImport: (id) => request(`/front/me/imports/${id}`, { method: 'DELETE', auth: true }),
  cancelSubmission: (id) => request(`/front/me/imports/${id}/cancel-submission`, { method: 'POST', auth: true }),
  publications: () => request('/front/me/publications', { auth: true }),
  withdraw: (id, reason) => request(`/front/me/publications/${id}/withdrawals`, { method: 'POST', data: { reason }, auth: true }),
}
