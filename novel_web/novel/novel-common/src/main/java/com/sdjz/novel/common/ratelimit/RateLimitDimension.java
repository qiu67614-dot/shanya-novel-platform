package com.sdjz.novel.common.ratelimit;

/**
 * 限流维度：决定「按谁计数」。
 *
 * <p>Nginx 那层只能按 IP（看不到 JWT），所以同一个出口下的用户共用一个桶；
 * 到了这里可以按用户身份精确计数，这是这一层存在的唯一理由。
 */
public enum RateLimitDimension {

    /**
     * 按用户 ID 限流。取不到用户（游客、token 失效）时<b>自动降级为 IP</b>，
     * 不需要调用方分别处理——这正是「游客没有 ID」的解法：
     * 有身份享受独立额度，没身份退回到共享 IP 桶。
     */
    USER,

    /** 强制按 IP 限流。用于游客为主的接口，或必须限制单个来源的场景。 */
    IP,

    /** 全局限流：全站共用一个桶，与来源无关。用于导入这类必须控制总量的重型操作。 */
    GLOBAL
}
